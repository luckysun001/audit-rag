    # 报告生成
    AUDIT_REPORT_GENERATION = AUDIT_REPORT_GENERATION_PROMPT

    @classmethod
    def get_prompt(cls, prompt_name: str):
        """获取指定名称的 Prompt 模板"""
        return getattr(cls, prompt_name.upper(), None)

    @classmethod
    def list_prompts(cls) -> list:
        """列出所有可用的 Prompt 模板"""
        return [
            attr for attr in dir(cls)
            if not attr.startswith('_') and isinstance(getattr(cls, attr), ChatPromptTemplate)
        ]
