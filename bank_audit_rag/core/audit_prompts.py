class BankAuditPrompts:
    """银行审计 Prompt 模板集合"""

    # 信贷审计
    LOAN_THREE_REVIEW = LOAN_THREE_REVIEW_PROMPT
    CONTRACT_COMPLIANCE = CONTRACT_COMPLIANCE_PROMPT

    # 合规审计
    REGULATORY_COMPLIANCE = REGULATORY_COMPLIANCE_PROMPT
